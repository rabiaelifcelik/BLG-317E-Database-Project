class People:
    def __init__(self,
                 person_id,
                 primary_name,
                 birth_year,
                 death_year,
                 primary_profession,
                 known_for_title):

        self.person_id=person_id
        self.primary_name=primary_name
        self.birth_year=birth_year
        self.death_year=death_year
        self.primary_profession=primary_profession
        self.known_for_title=known_for_title
